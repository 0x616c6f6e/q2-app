/** Regenerate launcher icons from SVG at their native target sizes. Requires Node.js + sharp. */
const fs = require('node:fs/promises');
const path = require('node:path');
const sharp = require('sharp');
const root = path.resolve(__dirname, '..');

async function main() {
    const profiles = JSON.parse(await fs.readFile(path.join(root, 'artwork/icon-profiles.json'), 'utf8'));
    const sources = {
        'assets/app-default.png': 'app-default.svg',
        'settings': 'system-settings-icon.svg',
        'music-player': 'music.svg',
    };
    let count = 0;
    const apps = await fs.readdir(path.join(root, 'apps'), {withFileTypes: true});
    for (const entry of apps.sort((a, b) => a.name.localeCompare(b.name))) {
        if (!entry.isDirectory()) continue;
        const app = path.join(root, 'apps', entry.name);
        const manifest = JSON.parse(await fs.readFile(path.join(app, 'manifest.json'), 'utf8'));
        const source = manifest.icon === 'assets/app-default.png'
            ? sources[manifest.icon] : sources[entry.name];
        if (!source) throw new Error(`No vector source for ${entry.name}: ${manifest.icon}`);
        for (const resolution of manifest.supported_resolutions || []) {
            const size = profiles[resolution];
            if (!Number.isInteger(size) || size < 1 || size > 512)
                throw new Error(`Missing or invalid icon size: ${resolution}`);
            const directory = path.join(app, 'assets', resolution);
            await fs.mkdir(directory, {recursive: true});
            // Render vector geometry above the target resolution, then antialias to native pixels.
            const png = await sharp(path.join(root, 'artwork/icons', source), {density: 384})
                .resize(size, size, {fit: 'contain', kernel: 'lanczos3'})
                .ensureAlpha().png({compressionLevel: 9, palette: false}).toBuffer();
            if (png.length > 256 * 1024) throw new Error(`Icon exceeds package limit: ${entry.name}`);
            await fs.writeFile(path.join(directory, path.basename(manifest.icon)), png);
            count++;
        }
    }
    // Use one profile source for artwork and Lua sizing; no independent magic-number copies.
    const lua = '-- Generated by scripts/generate_resolution_icons.cjs; edit artwork/icon-profiles.json.\n'
        + 'return {\n'
        + Object.entries(profiles).map(([key, value]) => `    ["${key}"] = ${value},\n`).join('')
        + '}\n';
    await fs.writeFile(path.join(root, 'apps/homepage/src/icon_profiles.lua'), lua);
    console.log(`Generated ${count} resolution-specific launcher PNGs and Home size profiles.`);
}
main().catch(error => { console.error(error.message); process.exitCode = 1; });
